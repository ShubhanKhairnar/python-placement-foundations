celcius = float(input("Enter temperature in Celsius: "))
Fahrenheit_Result = (celcius * 9/5) + 32
print(f"{celcius:.1f} degrees Celsius is equal to {Fahrenheit_Result:.1f} degrees Fahrenheit.")

fahrenheit = float(input("Enter temperature in Fahrenheit: "))
Celsius_Result = (fahrenheit - 32) * 5/9
print(f"{fahrenheit:.1f} degrees Fahrenheit is equal to {Celsius_Result:.1f} degrees Celsius.")